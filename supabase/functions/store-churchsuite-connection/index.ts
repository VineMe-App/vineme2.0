// Setup type definitions for built-in Supabase Runtime APIs
import "@supabase/functions-js/edge-runtime.d.ts"
import { createClient } from 'jsr:@supabase/supabase-js@2';

Deno.serve(async (req) => {
  try {
    const { church_id, client_id, client_secret } = await req.json();
    console.log(church_id, client_id, client_secret)

    // Use service role key so we can access Vault
    const supabase = createClient(
      Deno.env.get('SUPABASE_URL')!,
      Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!,
    );

    const { data, error } = await supabase.rpc('create_churchsuite_connection', {
      p_church_id: church_id,
      p_identifier: client_id,
      p_secret: client_secret,
    });

    if (error) throw error;

    return Response.json({ connectionId: data });
  } catch (err) {
    return Response.json({ error: err.message }, { status: 500 });
  }
});

